import express from 'express';

const app = express();
const PORT = 3000;

// Это "маршрут". Когда фронтенд (или браузер) обратится к серверу, он получит этот ответ
app.get('/', (req, res) => {
    res.send('Привет! Бэкенд для карты Львова успешно работает!');
});

// Запускаем сервер, чтобы он начал слушать запросы
app.listen(PORT, () => {
    console.log(`Сервер запущен. Открой в браузере: http://localhost:${PORT}`);
});